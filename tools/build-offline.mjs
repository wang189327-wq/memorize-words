/** Generate the complete, content-addressed web shell; user books/API responses are never inputs. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const excluded = new Set(['sw.js', 'offline-assets.js', 'version-reset-1.json']);
function files(directory = 'web') {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const name = path.join(directory, entry.name);
    if (entry.isDirectory()) return files(name);
    const relative = path.relative('web', name).replaceAll('\\', '/');
    return !excluded.has(relative) && !relative.endsWith('package.json') ? [relative] : [];
  });
}
const assets = files()
  .sort()
  .map((file) => ({
    path: file,
    sha256: crypto
      .createHash('sha256')
      .update(fs.readFileSync(path.join('web', file)))
      .digest('hex'),
  }));
const version = crypto
  .createHash('sha256')
  .update(JSON.stringify(assets))
  .digest('hex')
  .slice(0, 24);
const raw =
  '// Generated by tools/build-offline.mjs. Never includes personal data.\nself.WORDMEMO_SHELL = ' +
  JSON.stringify({ version, assets }, null, 2) +
  ';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync('web/offline-assets.js', 'utf8') !== raw)
    throw Error(
      'Offline asset manifest is stale. Run npm run generate after source/config changes.',
    );
} else fs.writeFileSync('web/offline-assets.js', raw);
console.log(`Offline shell ${version}: ${assets.length} static assets`);
