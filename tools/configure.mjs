import fs from 'node:fs';

export function validateConfig(config) {
  if (!/^[a-z][\w]*(\.[a-z][\w]*)+$/.test(config.applicationId)) {
    throw new Error('applicationId must be a valid Android application identifier');
  }
  if (
    !/^\d+\.\d+(?:\.\d+)?$/.test(config.versionName) ||
    !Number.isSafeInteger(config.versionCode) ||
    config.versionCode < 1
  ) {
    throw new Error('Invalid versionName or versionCode');
  }
  if (config.updates.enabled) {
    for (const key of ['manifestUrl', 'releaseBase']) {
      const url = new URL(config.updates[key]);
      if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash) {
        throw new Error(`${key} must be a plain HTTPS URL`);
      }
    }
    if (!config.updates.releaseBase.endsWith('/')) throw new Error('releaseBase must end in /');
  }
  return config;
}

const config = validateConfig(JSON.parse(fs.readFileSync('app.config.json', 'utf8')));
fs.writeFileSync(
  'web/config.js',
  `// Generated by npm run configure; edit app.config.json.\nwindow.WORDMEMO_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`Configured ${config.name} ${config.versionName} (${config.versionCode})`);
